const router = require('express').Router();
const rateLimit = require('express-rate-limit');
const controller = require('../controllers/authController');
const validate = require('../middleware/validate');
const { verifyCsrfToken } = require('../middleware/csrf');
const { requireAuth } = require('../middleware/auth');
const schemas = require('../validators/schemas');

const loginLimiter = rateLimit({ windowMs: 15 * 60 * 1000, limit: 10, standardHeaders: 'draft-7', legacyHeaders: false, message: 'Too many sign-in attempts. Try again later.' });
const registrationLimiter = rateLimit({ windowMs: 60 * 60 * 1000, limit: process.env.NODE_ENV === 'test' ? 30 : 5, standardHeaders: 'draft-7', legacyHeaders: false, message: 'Too many account attempts. Try again later.' });
router.get('/register', controller.showRegister);
router.post('/register/send-otp', registrationLimiter, verifyCsrfToken, validate(schemas.emailOtp), controller.sendRegistrationOtp);
router.post('/register', registrationLimiter, verifyCsrfToken, validate(schemas.register), controller.register);
router.get('/forgot-password', controller.showForgotPassword);
router.post('/forgot-password/send-code', registrationLimiter, verifyCsrfToken, validate(schemas.emailOtp), controller.sendPasswordResetOtp);
router.post('/forgot-password/reset', registrationLimiter, verifyCsrfToken, validate(schemas.passwordReset), controller.resetPassword);
router.get('/login', controller.showLogin);
router.post('/login', loginLimiter, verifyCsrfToken, validate(schemas.login), controller.login);
router.post('/logout', requireAuth, verifyCsrfToken, controller.logout);
router.get('/dashboard', requireAuth, controller.dashboard);
router.get('/profile', requireAuth, controller.profile);
router.post('/profile', requireAuth, verifyCsrfToken, controller.updateProfile);
router.get('/profile/change-password', requireAuth, controller.showChangePassword);
router.post('/profile/change-password', requireAuth, verifyCsrfToken, validate(schemas.changePassword), controller.changePassword);
router.get('/notifications', requireAuth, controller.notifications);
router.post('/notifications/read-all', requireAuth, verifyCsrfToken, controller.readAllNotifications);
router.post('/notifications/:id/delete', requireAuth, verifyCsrfToken, controller.deleteNotification);
router.post('/notifications/clear', requireAuth, verifyCsrfToken, controller.clearNotifications);
module.exports = router;
